// Builds public/workshop/course-outline.js: each course's objectives and its sessions (time, objective,
// content or method, expected outcome), taken from the course materials, for the training report.
//   node tests/workshop/build-course-outline.mjs          writes the file
//   import { buildOutline } from "./build-course-outline.mjs"   (the test compares it with the file)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const W = new URL("../../public/workshop/", import.meta.url);
const text = (h) => String(h || "").replace(/<br\s*\/?>/gi, " ").replace(/<[^>]+>/g, " ").replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/\*\*/g, "").replace(/\s+/g, " ").trim();
const items = (h) => [...String(h || "").matchAll(/<li>([\s\S]*?)<\/li>/g)].map((m) => text(m[1])).filter(Boolean);

function employeeData() {
  const ctx = { window: {} }; vm.createContext(ctx);
  for (const f of ["voice", "s1", "s2", "s3", "s4", "s5", "s6", "s7", "s8", "s9", "s10", "meta", "agenda"])
    vm.runInContext(readFileSync(new URL("data/" + f + ".js", W), "utf8"), ctx);
  const w = ctx.window;
  return { SESS: [w.D_VOICE, w.D_S1, w.D_S2, w.D_S3, w.D_S4, w.D_S5, w.D_S6, w.D_S7, w.D_S8, w.D_S9, w.D_S10], DAYS: w.D_META.DAYS, AGENDA: w.D_AGENDA };
}
function representativeData() {
  const html = readFileSync(new URL("representative/index.html", W), "utf8");
  const m = html.match(/window\.D_REP = (\{[\s\S]*?\});\n/);
  const d = JSON.parse(m[1]);
  return { SESS: d.SESS, DAYS: d.DAYS, AGENDA: d.AGENDA_HTML };
}
function csoData() {
  const html = readFileSync(new URL("cso/index.html", W), "utf8");
  const m = html.match(/window\.D_CSO = (\{[\s\S]*?\});\n/);
  return JSON.parse(m[1]);
}
function sessions(data, pick) {
  const S = Object.fromEntries(data.SESS.map((s) => [s.id, s]));
  const out = [];
  data.DAYS.forEach((d, di) => d.items.forEach((it) => {
    if (it.kind !== "session" || !S[it.id]) return;
    const s = S[it.id], p = s.plan || {};
    out.push(Object.assign({ n: s.n, day: di + 1, start: it.start, end: it.end, title: text(s.title) }, pick(p)));
  }));
  return out;
}
export function buildOutline() {
  const e = employeeData();
  const eObj = e.AGENDA.slice(e.AGENDA.indexOf("कार्यक्रमको उद्देश्य</h2>"));
  const eSec = eObj.slice(0, eObj.indexOf("<h2", 10));
  const eOut = e.AGENDA.slice(e.AGENDA.indexOf("अपेक्षित उपलब्धि</h2>"));
  const employee = {
    main: text((eSec.match(/मुख्य उद्देश्य:<\/strong>([\s\S]*?)<\/p>/) || [])[1]),
    objectives: items(eSec),
    outcomes: items(eOut.slice(0, eOut.indexOf("<h2", 10))),
    sessions: sessions(e, (p) => ({ objective: text(p.objective), content: text(p.content), outcome: text(p.outcome) })),
  };
  const r = representativeData();
  const rObj = r.AGENDA.slice(r.AGENDA.indexOf("कार्यशालाका उद्देश्यहरू"));
  const representative = {
    main: text((r.AGENDA.match(/<p>([^<]*उद्देश्यले[\s\S]*?)<\/p>/) || [])[1]),
    objectives: items(rObj.slice(0, rObj.indexOf("</ol>") + 5)),
    outcomes: [text((r.AGENDA.match(/अपेक्षित उपलब्धि:<\/strong>([\s\S]*?)<\/p>/) || [])[1])].filter(Boolean),
    sessions: sessions(r, (p) => ({ objective: "", content: text(p.method), outcome: text(p.outcome) })),
  };
  const c = csoData();
  const cso = {
    main: text(c.OBJECTIVE),
    objectives: c.OUTCOMES.map(text),
    outcomes: [],
    sessions: sessions(c, (p) => ({ objective: text(p.objective), content: text(p.steps), outcome: text(p.outcome) })),
  };
  return { employee, representative, cso };
}
export function outlineFile() {
  return "/* Generated by tests/workshop/build-course-outline.mjs from the course materials: do not edit by hand.\n" +
    " * Each course's objectives and sessions, in the base wording of its level (the report rewords them\n" +
    " * for the event's level and organiser). */\nwindow.COURSE_OUTLINE = " + JSON.stringify(buildOutline(), null, 1) + ";\n";
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL("course-outline.js", W), outlineFile());
  const o = buildOutline();
  for (const k of Object.keys(o)) console.log(k, "objectives", o[k].objectives.length, "outcomes", o[k].outcomes.length, "sessions", o[k].sessions.length, "| main:", o[k].main.slice(0, 70));
}
