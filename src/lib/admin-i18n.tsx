export function useT() {
  const { lang } = useI18n();
  return (s: string) => (lang === "ne" ? NE[s] ?? s : s);
}

/** Translates a string child; anything else passes through unchanged. */
export function tr(lang: string, v: ReactNode): ReactNode {
  return lang === "ne" && typeof v === "string" ? NE[v] ?? v : v;
}

export function Tx({ children }: { children: string }) {
  const t = useT();
  return <>{t(children)}</>;
}
